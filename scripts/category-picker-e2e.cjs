const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { _electron } = require(process.env.ANSHELF_PLAYWRIGHT || 'playwright');
const { Library } = require('../core/library.cjs');
const root = path.resolve(__dirname, '..');

async function main() {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'anshelf-category-picker-'));
  const data = path.join(temporary, 'library');
  const output = path.join(root, 'test-output/category-picker');
  await fs.mkdir(output, { recursive: true });
  const library = await Library.open(data);
  const urban = await library.createCategory('都市人物', null, 'ordinary');
  const female = await library.createCategory('女', urban.id, 'ordinary');
  const lead = await library.createCategory('主角', female.id, 'ordinary');
  for (let index = 0; index < 24; index++) await library.createCategory(`分类 ${String(index).padStart(2, '0')}`, null, 'ordinary');
  const background = library.snapshot().categories.find(item => item.name === '背景');
  const outdoor = await library.createCategory('户外', background.id, 'ordinary');
  const source = path.join(temporary, '分类演示素材.fla');
  const demo = (await fs.readdir(path.join(root, 'demo'))).find(name => name.endsWith('.fla'));
  await fs.copyFile(path.join(root, 'demo', demo), source);
  await fs.writeFile(path.join(temporary, '分类演示素材.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a0soAAAAASUVORK5CYII=', 'base64'));
  const imported = await library.importPaths([source], { categoryId: urban.id });
  const asset = imported.assets[0];
  const checks = [], errors = [];
  let app, page;
  try {
    app = await _electron.launch({ executablePath: process.env.ANSHELF_UI_EXECUTABLE || require(path.join(root, 'node_modules/electron')), args: [...(process.env.ANSHELF_UI_EXECUTABLE ? [] : [root]), '--user-data-dir=' + path.join(temporary, 'profile')], env: { ...process.env, ANSHELF_DATA_DIR: data }, timeout: 60000 });
    page = await app.firstWindow();
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    await page.waitForSelector('[data-action="import"][data-mode="ordinary"]');
    await page.evaluate(() => localStorage.setItem('anshelf-check-updates-on-start', 'false'));
    await page.locator('[data-action="import"][data-mode="ordinary"]').click();
    const trigger = page.locator('[data-category-trigger="import-category"]');
    assert.equal(await trigger.count(), 1, 'import uses the themed category picker');
    assert.equal(await page.locator('#import-category').isVisible(), false);
    assert.equal(await page.locator('#preview-resolution').isVisible(), false, 'resolution also uses the themed picker');
    const resolution = page.locator('[data-select-trigger="preview-resolution"]');
    assert.equal(await resolution.isDisabled(), true);
    await page.locator('#custom-preview-resolution').check();
    assert.equal(await resolution.isDisabled(), false);
    await resolution.click();
    assert.equal(await page.locator('[data-category-search]').count(), 0, 'short lists need no search box');
    assert.deepEqual(await page.locator('[data-category-option]').allTextContents().then(values => values.map(value => value.trim())), ['256 像素 · 轻量', '512 像素', '1024 像素', '2048 像素 · 2K']);
    await page.screenshot({ path: path.join(output, 'dark-resolution.png') });
    await page.locator('[data-category-option="2048"]').click();
    assert.equal(await page.locator('#preview-resolution').inputValue(), '2048');
    const before = await fs.readFile(path.join(data, 'library.json'), 'utf8');
    await trigger.click();
    const search = page.locator('[data-category-search]');
    await search.fill('都市 主角');
    assert.equal(await page.locator('[data-category-option]').count(), 1);
    assert.equal(await page.locator('[data-category-option]').getAttribute('data-category-option'), lead.id);
    assert.match(await page.locator('[data-category-option]').textContent(), /都市人物 \/ 女/);
    const dark = await page.locator('[data-category-popup]').evaluate(element => ({ background: getComputedStyle(element).backgroundColor, height: element.getBoundingClientRect().height, bottom: element.getBoundingClientRect().bottom, viewport: innerHeight }));
    assert.ok(dark.height < 430 && dark.bottom <= dark.viewport, JSON.stringify(dark));
    await page.screenshot({ path: path.join(output, 'dark-search.png') });
    await search.press('Escape');
    assert.equal(await page.locator('#dialog').evaluate(element => element.open), true);
    assert.equal(await page.locator('#import-category').inputValue(), '');
    assert.equal(await fs.readFile(path.join(data, 'library.json'), 'utf8'), before, 'search/Escape never writes metadata');
    checks.push('dark themed import picker searches deep full paths; Escape cancels without closing import or writing metadata');

    await trigger.click();
    await search.fill('都市');
    await search.press('ArrowDown');
    await search.press('ArrowDown');
    await search.press('ArrowUp');
    await search.press('ArrowDown');
    await search.press('Enter');
    assert.equal(await page.locator('#import-category').inputValue(), lead.id);
    assert.match(await trigger.textContent(), /都市人物 \/ 女 \/ 主角/);
    await page.locator('[data-action="import-create-child-category"]').click();
    await page.locator('#import-folder-name').fill('新建子分类');
    await page.locator('[data-action="save-import-folder"]').click();
    await page.waitForFunction(() => document.querySelector('[data-category-trigger="import-category"]')?.textContent.includes('新建子分类'));
    const created = (await page.evaluate(() => window.shelf.snapshot())).categories.find(item => item.name === '新建子分类');
    assert.equal(created.parentId, lead.id);
    assert.equal(await page.locator('#import-category').inputValue(), created.id);
    assert.equal(await page.locator('#preview-resolution').inputValue(), '2048');
    assert.match(await resolution.textContent(), /2048/);
    checks.push('keyboard commits one existing choice; child creation preserves the selected category and themed 2K resolution');

    await trigger.click();
    await search.fill('背景');
    await page.locator('#dialog-title').click();
    assert.equal(await page.locator('[data-category-popup]').count(), 0);
    assert.equal(await page.locator('#import-category').inputValue(), created.id);
    await page.locator('[data-action="close-dialog"]').click();
    await page.locator('[data-action="theme"][data-theme="warm"]').click();
    await page.locator('[data-action="import"][data-mode="ordinary"]').click();
    await trigger.click();
    const warm = await page.locator('[data-category-popup]').evaluate(element => ({ background: getComputedStyle(element).backgroundColor, listHeight: element.querySelector('[role="listbox"]').getBoundingClientRect().height, scrollHeight: element.querySelector('[role="listbox"]').scrollHeight }));
    assert.notEqual(warm.background, dark.background);
    assert.ok(warm.scrollHeight > warm.listHeight, JSON.stringify(warm));
    await page.screenshot({ path: path.join(output, 'warm-hierarchy.png') });
    await search.fill('背景 户外');
    await page.locator('[data-category-option]').click();
    assert.equal(await page.locator('#import-category').inputValue(), outdoor.id);
    await trigger.focus();
    await trigger.press('ArrowDown');
    await search.press('Escape');
    await page.locator('#custom-preview-resolution').check();
    await resolution.click();
    const shortList = page.locator('[data-category-popup] [role="listbox"]');
    await shortList.press('ArrowDown');
    await shortList.press('Escape');
    assert.equal(await page.locator('#preview-resolution').inputValue(), '512');
    await resolution.click();
    await shortList.press('ArrowDown');
    await shortList.press('ArrowDown');
    await page.screenshot({ path: path.join(output, 'warm-resolution.png') });
    await shortList.press('Enter');
    assert.equal(await page.locator('#preview-resolution').inputValue(), '2048');
    await page.locator('[data-action="close-dialog"]').click();
    checks.push('outside click cancels without changing selection; warm categories and resolution menus use app colors, long hierarchies scroll and keyboard selection/Escape both work');

    await page.locator('[data-action="create-category"]').click();
    assert.equal(await page.locator('#category-scope').isVisible(), false);
    const scope = page.locator('[data-select-trigger="category-scope"]');
    await scope.click();
    await page.locator('[data-category-option="effect"]').click();
    assert.equal(await page.locator('#category-scope').inputValue(), 'effect');
    await page.locator('[data-category-trigger="category-parent"]').click();
    await search.fill('都市 主角');
    await search.press('Enter');
    assert.equal(await page.locator('#category-parent').inputValue(), lead.id);
    assert.equal(await page.locator('#category-scope').inputValue(), 'ordinary');
    assert.equal(await page.locator('#category-scope').isDisabled(), true);
    assert.equal(await scope.isDisabled(), true);
    assert.match(await scope.textContent(), /普通素材/);
    await page.locator('[data-action="close-dialog"]').first().click();
    checks.push('category parent picker synchronizes the hidden select and inherited media scope');

    await page.locator(`.asset-card[data-asset="${asset.id}"] .card-information h3`).click();
    await page.locator('#inspector-toggle').click();
    const inspectorSelect = page.locator('#inspector select[data-field="category"]');
    assert.equal(await inspectorSelect.isVisible(), false);
    await page.locator('#inspector [data-category-trigger="asset-category"]').click();
    await search.fill('都市 主角');
    await search.press('Enter');
    await page.waitForFunction(({ id, categoryId }) => window.shelf.snapshot().then(snapshot => snapshot.assets.some(item => item.id === id && item.categoryId === categoryId)), { id: asset.id, categoryId: lead.id });
    await page.waitForSelector(`#inspector [data-category-id="${lead.id}"]`);
    assert.equal(await page.locator('#inspector [data-category-trigger="asset-category"]').evaluate(element => document.activeElement === element), true, 'inspector refresh must retain focus on the same material category trigger');
    checks.push('inspector category uses the same picker and commits the chosen category through the existing change event');
    await page.locator('[data-action="import"][data-mode="ordinary"]').click();
    const importIndexBeforeTab = await fs.readFile(path.join(data, 'library.json'), 'utf8');
    await trigger.click();
    await search.press('Tab');
    assert.equal(await page.locator('[data-action="import-create-category"]').evaluate(element => document.activeElement === element), true, 'Tab from category search proceeds after its trigger');
    await trigger.click();
    await search.press('Shift+Tab');
    assert.equal(await page.locator('#prefer-preview').evaluate(element => document.activeElement === element), true, 'Shift+Tab from category search proceeds before its trigger');
    await page.locator('#custom-preview-resolution').check();
    await resolution.click();
    await shortList.press('Tab');
    assert.equal(await page.locator('[data-action="import-files"]').evaluate(element => document.activeElement === element), true, 'Tab from resolution list proceeds after its trigger');
    await resolution.click();
    await shortList.press('Shift+Tab');
    assert.equal(await page.locator('#custom-preview-resolution').evaluate(element => document.activeElement === element), true, 'Shift+Tab from resolution list proceeds before its trigger');
    assert.equal(await page.locator('[data-category-popup]').count(), 0);
    assert.equal(await page.locator('#import-category').inputValue(), '');
    assert.equal(await page.locator('#preview-resolution').inputValue(), '512');
    assert.equal(await fs.readFile(path.join(data, 'library.json'), 'utf8'), importIndexBeforeTab);
    checks.push('inspector keeps trigger focus after refresh; Tab and Shift+Tab leave category search and short option menus in natural order without committing');
    assert.deepEqual(errors, []);
    const report = { passed: true, checks, pageErrors: errors };
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify(report, null, 2));
  } catch (error) {
    if (page && !page.isClosed()) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    throw error;
  } finally {
    if (app) await app.close().catch(() => {});
    await fs.rm(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
