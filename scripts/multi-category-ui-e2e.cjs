const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { _electron } = require(process.env.ANSHELF_PLAYWRIGHT || 'playwright');
const { Library } = require('../core/library.cjs');
const root = path.resolve(__dirname, '..');

async function main() {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'anshelf-shared-category-'));
  const data = path.join(temporary, 'library'), profile = path.join(temporary, 'profile');
  const output = process.env.ANSHELF_MULTI_CHECK_OUTPUT || path.join(root, 'test-output', 'multi-category');
  await fs.mkdir(output, { recursive: true });
  const library = await Library.open(data);
  const first = await library.createCategory('剧集一', null, 'ordinary');
  const second = await library.createCategory('剧集二', null, 'ordinary');
  const female = await library.createCategory('女', second.id, 'ordinary');
  const demo = (await fs.readdir(path.join(root, 'demo'))).find(name => name.endsWith('.fla'));
  const source = path.join(temporary, '都市人物_女主角.fla');
  await fs.copyFile(path.join(root, 'demo', demo), source);
  const original = await fs.readFile(source);
  const executablePath = process.env.ANSHELF_UI_EXECUTABLE || require(path.join(root, 'node_modules/electron'));
  const launch = () => _electron.launch({ executablePath, args: [...(process.env.ANSHELF_UI_EXECUTABLE ? [] : [root]), '--user-data-dir=' + profile], env: { ...process.env, ANSHELF_DATA_DIR: data }, timeout: 60000 });
  let app, page;
  const checks = [], errors = [];
  const snapshot = () => page.evaluate(() => window.shelf.snapshot());
  const waitCategories = async expected => page.waitForFunction(expected => document.querySelector('#asset-grid .asset-card') && window.shelf.snapshot().then(state => JSON.stringify(state.assets[0].categoryIds) === JSON.stringify(expected)), expected);
  const browse = async id => { await page.locator(`#categories .nav-item[data-id="${id}"]`).click(); await page.waitForTimeout(100); };
  try {
    app = await launch(); page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('#empty-state:not([hidden])');
    await app.evaluate(({ dialog }, source) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [source] }); }, source);
    await page.locator('[data-action="import"][data-mode="ordinary"]').click();
    await page.locator('#import-category').selectOption(first.id); await page.locator('#prefer-preview').uncheck();
    await page.locator('[data-action="import-files"]').click();
    await page.waitForFunction(() => window.shelf.snapshot().then(state => state.assets.length === 1 && state.assets[0].previewStatus === 'ready'));
    const asset = (await snapshot()).assets[0];
    assert.equal(await page.locator('.asset-card img').evaluate(image => image.complete && image.naturalWidth > 0), true);
    checks.push('real import renders a visible offline preview');
    await page.locator('.asset-card h3').click();
    assert.equal(await page.locator('#selection-bar [data-action="toggle-add-categories"]').isVisible(), true);
    await page.locator('#selection-bar [data-action="toggle-add-categories"]').click();
    await page.locator(`#selection-bar [data-action="add-to-category"][data-id="${female.id}"]`).click();
    await waitCategories([first.id, female.id]);
    assert.equal((await snapshot()).assets.length, 1);
    checks.push('add-to-category retains original category and shares one asset');
    await browse(first.id); assert.equal(await page.locator('.asset-card').count(), 1);
    await browse(second.id); assert.equal(await page.locator('.asset-card').count(), 1);
    await page.screenshot({ path: path.join(output, 'shared-in-second-series.png') });
    await page.locator('#filter').click(); await page.locator('[data-filter="hide-child-categories"]').click();
    assert.equal(await page.locator('.asset-card').count(), 0);
    await page.locator('#filter').click(); await page.locator('[data-filter="hide-child-categories"]').click();
    assert.equal(await page.locator('.asset-card').count(), 1);
    checks.push('category browsing and child-folder filter use all memberships');
    await page.locator('.asset-card [data-action="favorite"]').click();
    await page.locator('#navigation [data-id="favorites"]').click();
    await page.waitForSelector(`#subcategories [data-id="${female.id}"]`);
    assert.equal(await page.locator(`#subcategories [data-id="${first.id}"]`).count(), 1);
    await page.locator(`#subcategories [data-id="${female.id}"]`).click();
    assert.equal(await page.locator('.asset-card').count(), 1);
    checks.push('favorites expose both source category paths');
    await page.locator('.asset-card h3').click(); await page.locator('#selection-bar [data-action="toggle-inspector"]').click();
    await page.locator(`#inspector [data-action="remove-from-category"][data-category-id="${female.id}"]`).click();
    await page.waitForFunction(first => window.shelf.snapshot().then(state => state.assets[0].categoryIds.length === 1 && state.assets[0].categoryId === first), first.id);
    await page.locator('#toast [data-action="undo-assign"]').click();
    await waitCategories([first.id, female.id]);
    checks.push('remove one category and undo retain the source asset');
    await app.evaluate(({ shell }) => { global.__anshelfOpened = []; shell.openPath = async file => { global.__anshelfOpened.push(file); return ''; }; });
    await page.locator('.asset-card [data-action="open-animate"]').click();
    for (let attempt = 0; attempt < 100 && !(await app.evaluate(() => global.__anshelfOpened.length)); attempt++) await page.waitForTimeout(50);
    const opened = await app.evaluate(() => global.__anshelfOpened);
    assert.equal(path.basename(opened[0]), '都市人物_女主角.fla');
    assert.notEqual(opened[0], source); assert.deepEqual(await fs.readFile(opened[0]), original);
    assert.equal(path.dirname(path.dirname(opened[0])), path.join(data, 'opened'));
    checks.push('real UI open callback receives the meaningful protected working copy');
    await page.locator('#selection-bar [data-action="toggle-add-categories"]').click();
    await page.screenshot({ path: path.join(output, 'add-to-category.png') });
    await app.close(); app = await launch(); page = await app.firstWindow(); page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('.asset-card');
    assert.deepEqual((await snapshot()).assets[0].categoryIds, [first.id, female.id]);
    assert.deepEqual(await fs.readFile(source), original);
    checks.push('restart retains memberships and original bytes');
    assert.deepEqual(errors, []);
    const result = { passed: true, executablePath, checks, pageErrors: errors };
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify(result, null, 2)); console.log(JSON.stringify(result, null, 2));
  } catch (error) {
    if (page && !page.isClosed()) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: false, checks, error: error.message, pageErrors: errors }, null, 2)); throw error;
  } finally { if (app) await app.close().catch(() => {}); }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
