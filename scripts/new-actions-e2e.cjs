const fs = require('node:fs/promises');
const path = require('node:path');
const os = require('node:os');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { _electron } = require(process.env.ANSHELF_PLAYWRIGHT || 'playwright');
const { Library } = require('../core/library.cjs');
const root = path.resolve(__dirname, '..');

async function main() {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'anshelf-new-actions-'));
  const data = path.join(temporary, 'library');
  const output = process.env.ANSHELF_ACTIONS_OUTPUT || path.join(root, 'test-output/new-actions');
  await fs.mkdir(output, { recursive: true });
  const demo = (await fs.readdir(path.join(root, 'demo'))).find(name => name.endsWith('.fla'));
  const source = path.join(temporary, '中文武器.fla');
  await fs.copyFile(path.join(root, 'demo', demo), source);
  await fs.writeFile(path.join(temporary, '中文武器.png'), Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+a0soAAAAASUVORK5CYII=', 'base64'));
  const library = await Library.open(data);
  const category = await library.createCategory('特效分类', null, 'effect');
  const subcategory = await library.createCategory('武器子类', category.id, 'effect');
  const extraCategory = await library.createCategory('其他特效', null, 'effect');
  const imported = await library.importPaths([source], { mode: 'effect', categoryId: subcategory.id, previewResolution: 2048 });
  const asset = imported.assets[0];
  await library.addToCategory([asset.id], extraCategory.id);
  await library.updateAsset(asset.id, { tags: ['旋转', '武器'], favorite: true, liked: true });
  const checks = [], errors = [];
  const executablePath = process.env.ANSHELF_UI_EXECUTABLE || require(path.join(root, 'node_modules/electron'));
  let app, page;
  try {
    app = await _electron.launch({ executablePath, args: [...(process.env.ANSHELF_UI_EXECUTABLE ? [] : [root]), '--user-data-dir=' + path.join(temporary, 'profile')], env: { ...process.env, ANSHELF_DATA_DIR: data }, timeout: 60000 });
    page = await app.firstWindow();
    page.on('pageerror', error => errors.push(error.message));
    await page.waitForSelector('.asset-card');
    assert.equal(await page.locator('.asset-card [data-action="duplicate-file"]').count(), 1, 'card offers one-click copy');
    await app.evaluate(({ shell }) => { globalThis.revealedCopies = []; shell.showItemInFolder = file => globalThis.revealedCopies.push(file); });
    await page.locator(`[data-action="category"][data-id="${category.id}"]`).first().click();
    await page.locator('#search').fill('中文武器');
    await page.locator('.asset-card').hover();
    await page.locator('.asset-card [data-action="duplicate-file"]').click();
    await page.locator('#confirm-dialog[open]').waitFor();
    assert.match(await page.locator('#confirm-dialog').textContent(), /复制/);
    assert.equal(await page.locator('[data-confirm="cancel"]').evaluate(button => document.activeElement === button), true);
    await page.locator('[data-confirm="cancel"]').click();
    await page.waitForFunction(() => !document.body.classList.contains('is-busy'));
    await assert.rejects(fs.access(path.join(temporary, '中文武器 - 副本.fla')), { code: 'ENOENT' });
    assert.deepEqual(await app.evaluate(() => globalThis.revealedCopies), []);
    checks.push('copy requires a themed Chinese confirmation dialog with cancel focused; cancel creates no file and opens no Explorer window');
    await page.locator('.asset-card [data-action="duplicate-file"]').click();
    await page.locator('#confirm-dialog[open] [data-confirm="accept"]').click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已复制'));
    const afterCopy = await page.evaluate(() => window.shelf.snapshot());
    assert.equal(afterCopy.assets.length, 2, 'copy is automatically registered as an independent material');
    const copyAsset = afterCopy.assets.find(item => item.id !== asset.id);
    const copy = path.join(data, copyAsset.managedPath);
    assert.deepEqual(await fs.readFile(copy), await fs.readFile(source));
    assert.deepEqual(await app.evaluate(() => globalThis.revealedCopies), [copy]);
    assert.notEqual(copyAsset.managedPath, afterCopy.assets.find(item => item.id === asset.id).managedPath);
    assert.equal(copyAsset.assetType, 'effect');
    assert.equal(copyAsset.previewResolution, 2048);
    assert.deepEqual(copyAsset.tags, ['旋转', '武器']);
    assert.deepEqual(new Set([copyAsset.categoryId, ...copyAsset.categoryIds]), new Set([subcategory.id, extraCategory.id]));
    assert.equal(copyAsset.favorite, false);
    assert.equal(copyAsset.liked, false);
    assert.equal(copyAsset.likedAt, null);
    assert.equal(await page.locator('#search').inputValue(), '');
    assert.equal(await page.locator(`[data-action="category"][data-id="${category.id}"]`).first().evaluate(button => button.classList.contains('active')), true);
    await page.waitForSelector(`[data-asset="${copyAsset.id}"].selected`);
    checks.push('card creates one independent managed material, inherits type/categories/tags/2K preview settings, clears favorites/likes, preserves its visible parent category and selects the new card');
    await page.locator(`[data-asset="${copyAsset.id}"] [data-action="reveal-file"]`).click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent === '已定位这份独立素材文件');
    assert.deepEqual(await app.evaluate(() => globalThis.revealedCopies), [copy, copy]);
    await app.evaluate(() => { globalThis.revealedCopies = [globalThis.revealedCopies[0]]; });
    await page.locator('[data-action="category"][data-id="favorites"]').first().click();
    await page.locator(`[data-asset="${asset.id}"] [data-action="zoom-preview"]`).click();
    assert.equal(await page.locator('#dialog [data-action="duplicate-file"]').count(), 1);
    await page.locator('#dialog [data-action="duplicate-file"]').click();
    await page.locator('#confirm-dialog[open] [data-confirm="accept"]').click();
    for (let i = 0; i < 100 && (await app.evaluate(() => globalThis.revealedCopies.length)) < 2; i++) await page.waitForTimeout(50);
    const twiceCopied = await page.evaluate(() => window.shelf.snapshot());
    assert.equal(twiceCopied.assets.length, 3);
    const secondCopy = twiceCopied.assets.find(item => item.id !== asset.id && item.id !== copyAsset.id);
    await fs.access(path.join(data, secondCopy.managedPath));
    assert.notEqual(secondCopy.name, copyAsset.name);
    await page.waitForSelector(`[data-asset="${secondCopy.id}"].selected`);
    assert.equal(await page.locator('#dialog').evaluate(dialog => dialog.open), false);
    assert.equal(await page.locator(`[data-action="category"][data-id="${subcategory.id}"]`).first().evaluate(button => button.classList.contains('active')), true);
    checks.push('copy from favorites closes the old lightbox, creates a distinct readable name and reveals the un-favorited new card in its original category');
    const incoming = path.join(temporary, 'AN当前作品.fla');
    await fs.writeFile(incoming, Buffer.concat([await fs.readFile(source), Buffer.from('\nnew-document')]));
    await fs.copyFile(path.join(temporary, '中文武器.png'), path.join(temporary, 'AN当前作品.png'));
    const requestId = randomUUID();
    const inbox = path.join(data, 'bridge/document-import/inbox');
    const requestFile = path.join(inbox, requestId + '.json');
    await fs.mkdir(inbox, { recursive: true });
    await fs.writeFile(requestFile + '.tmp', JSON.stringify({ version: 1, requestId, file: incoming, createdAt: Date.now() }));
    await fs.rename(requestFile + '.tmp', requestFile);
    const resultFile = path.join(data, 'bridge/document-import/results', requestId + '.json');
    let receipt;
    for (let i = 0; i < 100; i++) {
      try { receipt = JSON.parse(await fs.readFile(resultFile, 'utf8')); break; } catch {}
      await page.waitForTimeout(100);
    }
    assert.equal(receipt?.ok, true, JSON.stringify(receipt));
    await page.locator('[data-action="category"][data-id="all"]').first().click();
    await page.waitForFunction(() => document.querySelector('#asset-count').textContent.includes('4 个'));
    assert.equal((await page.evaluate(() => window.shelf.snapshot())).assets.length, 4);
    assert.deepEqual(await fs.readFile(source), await fs.readFile(copy));
    checks.push('desktop receives real file-bridge request without restart and refreshes asset cards');

    const audioFiles = [];
    for (let i = 0; i < 61; i++) {
      const wav = Buffer.alloc(48);
      wav.write('RIFF'); wav.writeUInt32LE(40, 4); wav.write('WAVEfmt ', 8);
      wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
      wav.writeUInt32LE(8000, 24); wav.writeUInt32LE(16000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
      wav.write('data', 36); wav.writeUInt32LE(4, 40); wav.writeInt16LE(i, 44); wav.writeInt16LE(-i, 46);
      const file = path.join(temporary, `分页音频-${i.toString().padStart(2, '0')}.wav`);
      await fs.writeFile(file, wav); audioFiles.push(file);
    }
    await app.evaluate(({ dialog }, files) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: files }); }, audioFiles);
    const audioImport = await page.evaluate(() => window.shelf.importFiles({ mode: 'audio' }));
    assert.equal(audioImport.added, 61);
    await page.reload();
    await page.waitForSelector('.asset-card');
    await page.locator('[data-action="category"][data-id="audio"]').first().click();
    await page.locator('#sort').click(); await page.locator('[data-action="sort"][data-sort="oldest"]').click();
    await page.waitForSelector(`.asset-card[data-asset="${audioImport.assets[0].id}"]`);
    assert.match(await page.locator('#asset-pagination').textContent(), /第 1 \/ 2 页/);
    await page.locator(`.asset-card[data-asset="${audioImport.assets[0].id}"] [data-action="duplicate-file"]`).click();
    await page.locator('#confirm-dialog[open] [data-confirm="accept"]').click();
    await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('已复制'));
    const audioSnapshot = await page.evaluate(() => window.shelf.snapshot());
    const audioCopy = audioSnapshot.assets.find(item => item.kind === 'audio' && !audioImport.assets.some(original => original.id === item.id));
    assert.ok(audioCopy);
    assert.equal(audioCopy.kind, 'audio');
    assert.deepEqual(await fs.readFile(path.join(data, audioCopy.managedPath)), await fs.readFile(audioFiles[0]));
    await page.waitForSelector(`.asset-card[data-asset="${audioCopy.id}"].selected`);
    assert.match(await page.locator('#asset-pagination').textContent(), /第 2 \/ 2 页/);
    assert.equal(await page.locator('[data-action="sort"][data-sort="oldest"]').getAttribute('aria-checked'), 'true');
    checks.push('audio copying keeps the audio view and oldest-first order, automatically changes to the new card page and selects the independent copy');
    assert.deepEqual(errors, []);
    await page.screenshot({ path: path.join(output, 'new-actions.png') });
    await fs.writeFile(path.join(output, 'result.json'), JSON.stringify({ passed: true, checks, pageErrors: errors }, null, 2));
    console.log(JSON.stringify({ passed: true, checks, pageErrors: errors }, null, 2));
  } catch (error) {
    if (page && !page.isClosed()) await page.screenshot({ path: path.join(output, 'failure.png') }).catch(() => {});
    throw error;
  } finally {
    if (app) await app.close().catch(() => {});
    await fs.rm(temporary, { recursive: true, force: true });
  }
}
main().catch(error => { console.error(error); process.exitCode = 1; });
